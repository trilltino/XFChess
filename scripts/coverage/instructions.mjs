import fs from 'node:fs';
import path from 'node:path';
import { root, readJson, writeJson, rustTests, checkedDocument } from './lib.mjs';

const source = fs.readFileSync(path.join(root, 'programs/xfchess-game/src/lib.rs'), 'utf8');
const program = source.slice(source.indexOf('#[program]'));
const names = [...program.matchAll(/\bpub fn (\w+)/g)].map((m) => m[1]).sort();
if (names.length < 70 || new Set(names).size !== names.length) throw new Error('Instruction discovery failed');
const cells = ['success', 'wrong_signer', 'wrong_account', 'wrong_state', 'arithmetic_edge'];
const tests = rustTests(['programs/xfchess-game/tests']);
const manifestFile = 'docs/coverage/instruction-evidence.json';
if (process.argv.includes('--bootstrap')) {
  if (fs.existsSync(path.join(root, manifestFile))) throw new Error('Instruction evidence already exists');
  writeJson(manifestFile, Object.fromEntries(names.map((name) => [name, Object.fromEntries(cells.map((cell) => [cell, []]))])));
}
const evidence = readJson(manifestFile);
const rows = [];
for (const name of names) {
  if (!(name in evidence)) throw new Error(`New instruction ${name} needs success and negative evidence`);
  const row = evidence[name];
  for (const cell of cells) {
    if (!Array.isArray(row[cell])) throw new Error(`${name}.${cell} must be a list of test references`);
    for (const ref of row[cell]) if (!tests.has(ref)) throw new Error(`Unknown test ${ref} for ${name}.${cell}`);
  }
  const candidates = [...tests].filter(([, body]) => body.includes(name) || body.includes(name.split('_').map((w) => w[0].toUpperCase()+w.slice(1)).join(''))).map(([ref]) => ref);
  rows.push(`| \`${name}\` | ${cells.map((cell) => row[cell].length ? row[cell].map((ref) => `\`${ref}\``).join('<br>') : 'gap').join(' | ')} | ${candidates.length} |`);
}
for (const name of Object.keys(evidence)) if (!names.includes(name)) throw new Error(`Removed instruction ${name}: review evidence explicitly`);
const filled = Object.values(evidence).reduce((sum, row) => sum + cells.filter((cell) => row[cell].length).length, 0);
checkedDocument('docs/coverage/instructions.md', `# Instruction matrix\n\nGenerated by \`node scripts/coverage/instructions.mjs\`. ${names.length} instructions; ${filled}/${names.length * cells.length} reviewed cells.\n\nCells require reviewed assertion evidence. Candidate counts are source references only; they do not prove execution or negative coverage. Existing gaps are retained for WP1/WP7.\n\n| Instruction | Success | Wrong signer | Wrong account/PDA | Wrong state | Arithmetic edge | Candidate tests |\n|---|---|---|---|---|---|---|\n${rows.join('\n')}\n`);
